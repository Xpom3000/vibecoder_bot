"""Простой keyword-фильтр промпт-инъекций — вторая линия защиты поверх
инструкций в системном промпте DeepSeek (services/ai.py).

Работает ДО обращения к ИИ: если во входящем тексте есть подозрительная
фраза (просьба забыть инструкции, показать системный промпт, сменить роль
бота и т.п.) — вопрос сразу отклоняется, без траты запроса к DeepSeek.

Это эвристика по ключевым словам, а не непробиваемая защита: изощрённая
формулировка без этих слов всё ещё может пройти сюда — тогда её должен
поймать сам системный промпт модели. Список стоит пополнять по мере того,
как будут появляться новые попытки обхода.
"""
import re

# Регистронезависимые подстроки. Пишем в нижнем регистре — сравнение идёт
# с уже приведённым к нижнему регистру текстом.
SUSPICIOUS_PATTERNS = [
    # Попытки отменить/обойти инструкции
    r"игнориру\w* (все |вс[её] )?(инструкц|правил|систем)",
    r"забудь\w* (все |вс[её] )?(инструкц|правил|систем|про[мш]пт)",
    r"ignore (all |previous |the )?instructions",
    r"disregard (all |previous |the )?instructions",
    r"без\s*ограничени",
    r"no restrictions",
    r"без\s*цензур",
    r"jailbreak",
    r"dan\s*mode",
    r"developer\s*mode",
    r"режим\s*разработчик",

    # Попытки раскрыть системный промпт
    r"систем\w*\s*промпт",
    r"систем\w*\s*инструкц",
    r"system\s*prompt",
    r"(твои?|свои?)\s*(настоящие\s*)?инструкц",
    r"your\s*instructions",
    r"покажи\w*\s*(свой|весь)?\s*(промпт|код|инструкц)",
    r"(процитируй|перескажи|переведи)\w*\s*(свой\s*)?промпт",
    r"repeat\s*your\s*(prompt|instructions)",
    r"reveal\s*your\s*(prompt|instructions)",
    r"print\s*your\s*(prompt|instructions)",
    r"вывед\w*\s*весь\s*текст\s*выше",
    r"что\s*у\s*тебя\s*в\s*систем",

    # Попытки сменить роль/личность бота
    r"притворись\w*",
    r"pretend\s*you",
    r"act\s*as\s*(if\s*)?(a|an)?\s*\w+",
    r"веди\s*себя\s*как",
    r"ты\s*теперь\s*\w+",
    r"you\s*are\s*now\s*\w+",
    r"с\s*этого\s*момента\s*ты",
    r"забудь\w*,?\s*что\s*ты",
]

_COMPILED = [re.compile(p, re.IGNORECASE) for p in SUSPICIOUS_PATTERNS]


def is_suspicious(text: str) -> bool:
    """True, если текст похож на попытку промпт-инъекции."""
    return any(pattern.search(text) for pattern in _COMPILED)
